package qa.guru;

public class Main {
    public static void main(String[] args){
        // Объявляем переменные
        int a = 15;
        int b = 7;
        
        // Сложение
        int sum = a + b;
        
        // Вычитание
        int difference = a - b;
        
        // Вывод результатов
        System.out.println("Число a = " + a);
        System.out.println("Число b = " + b);
        System.out.println("Сложение (a + b) = " + sum);
        System.out.println("Вычитание (a - b) = " + difference);
    }
}
